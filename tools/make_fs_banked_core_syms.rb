#!/usr/bin/env ruby
# frozen_string_literal: true

# Generate the core-symbol shim the banked filesystem module
# links against.
#
# The module in fs_banked/fs_service.c is linked as its own
# image, separate from the kernel.  It calls the resident
# kernel - the volume, file, directory, inode, allocator,
# path and superblock layers, the TTY device, the block
# cache and libc - and those calls are absolute addresses:
# the module is mapped into window 1 at 0x4000, and the
# functions it calls live in windows 0 and 2, which the
# trampoline's temp map leaves in place.
#
# An absolute address is a build-derived value: it moves
# whenever the kernel link changes.  So the module is linked
# *after* the kernel, against a shim generated from
# build/kernel.map that defines every kernel global at the
# address the kernel really placed it.  sdasz80 turns
# `_sym = 0xADDR` into an absolute symbol, and the linker
# resolves the module's cross-module calls against it - the
# call lands on the resident function itself.
#
# The shim must not define what the module defines: the
# kernel link now contains the wrappers in kernel/fs_banked.c,
# which carry the same muzix_fs_service_* names as the real
# functions in the module, and the module also defines
# muzix_fs_banked_dispatch().  Defining either set twice
# would make the module link fail with "Multiple definition",
# which is the correct failure - the two halves are the same
# interface and must not both be present.
#
# Usage: make_fs_banked_core_syms.rb <kernel.map> <output.s>

map_path = ARGV[0] or abort 'usage: make_fs_banked_core_syms.rb <kernel.map> <output.s>'
out_path = ARGV[1] or abort 'usage: make_fs_banked_core_syms.rb <kernel.map> <output.s>'

# A global symbol line: an address, a name and the module that
# defines it.  The area headers (line starts with the area
# name at column 0) and the .ABS. block's two-token extent
# lines (l__CODE, s__DATA, ...) do not match this shape.
SYMBOL = /\A\s+([0-9A-Fa-f]{4,8})\s+(_[A-Za-z0-9_]+)\s+\S+\s*\z/

# Names the module owns.  See the header comment.
EXCLUDED = /\A_muzix_fs_service_|\A_muzix_fs_banked_/

symbols = []
File.foreach(map_path, mode: 'rb') do |line|
  m = line.match(SYMBOL)
  next unless m
  next if m[2].match?(EXCLUDED)
  symbols << [m[2], m[1].to_i(16)]
end

if symbols.empty?
  abort "FAIL: no kernel symbols found in #{map_path}"
end

  File.open(out_path, 'w') do |f|
    f.puts '; Generated by tools/make_fs_banked_core_syms.rb.'
    f.puts '; Do not edit: the addresses are the kernel link'
    f.puts '; output.'
    f.puts ';'
    f.puts "; #{symbols.size} kernel globals, each defined at the"
    f.puts '; absolute address build/kernel.map placed it, so the'
    f.puts '; banked filesystem module resolves its calls into the'
    f.puts '; resident kernel.'
    f.puts '.module fs_banked_core_syms'
    symbols.sort.each do |name, addr|
      f.puts ".globl #{name}"
      f.puts "#{name} = 0x#{format('%X', addr)}"
    end
  end

puts "  fs_banked core symbol shim: #{symbols.size} symbols -> #{out_path}"
